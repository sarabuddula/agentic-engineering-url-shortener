package com.agenticengineering.urlshortener.shortener.api;

import com.agenticengineering.urlshortener.shared.api.RequestAttributes;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.util.UUID;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.slf4j.MDC;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.stereotype.Component;
import org.springframework.web.filter.OncePerRequestFilter;

/**
 * Correlation id per request (T022; NFR-005, plan section 7). The id is generated by the server, placed in the logging
 * context (MDC) and on the request for the error handler, and written in one access line per request. The access line
 * holds method, path, status, request id and the authenticated key ID only: never headers (X-API-Key), query strings or
 * bodies (NFR-001).
 */
@Component
@Order(Ordered.HIGHEST_PRECEDENCE)
public class RequestCorrelationFilter extends OncePerRequestFilter {

    public static final String MDC_REQUEST_ID = "request_id";

    /** Request attribute the authentication step sets to the resolved key ID (never the key itself). */
    public static final String KEY_ID_ATTRIBUTE = RequestAttributes.KEY_ID;

    private static final Logger ACCESS = LoggerFactory.getLogger("access");

    @Override
    protected void doFilterInternal(HttpServletRequest request, HttpServletResponse response, FilterChain chain)
            throws ServletException, IOException {
        String requestId = "req-" + UUID.randomUUID();
        request.setAttribute(GlobalExceptionHandler.REQUEST_ID_ATTRIBUTE, requestId);
        MDC.put(MDC_REQUEST_ID, requestId);
        try {
            chain.doFilter(request, response);
        } finally {
            Object keyId = request.getAttribute(KEY_ID_ATTRIBUTE);
            ACCESS.info("request method={} path={} status={} request_id={} key_id={}", request.getMethod(),
                    request.getRequestURI(), response.getStatus(), requestId, keyId == null ? "-" : keyId);
            MDC.remove(MDC_REQUEST_ID);
        }
    }
}
