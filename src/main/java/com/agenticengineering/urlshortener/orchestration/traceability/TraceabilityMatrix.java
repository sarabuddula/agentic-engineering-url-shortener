package com.agenticengineering.urlshortener.orchestration.traceability;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Stream;

/**
 * Traceability matrix (T090; plan section 13, FR-030): the mapping manifest joined with the demonstration run records
 * exported under docs/evidence/runs (the persisted run tables read through the REVIEWER API), rendered in both
 * directions - requirement to tasks, ADRs, tests and evidence, grouped by family; test or evidence file back to
 * requirements - with the runs each evidence file stands for and the checker's orphan status.
 */
public final class TraceabilityMatrix {

    private static final List<String> FAMILIES = List.of("FR", "NFR", "SC", "SCN", "US", "PVT");
    private static final ObjectMapper JSON = new ObjectMapper();

    private TraceabilityMatrix() {
    }

    public static String render(MappingManifest manifest, ManifestChecker.Report report, Path root) throws IOException {
        StringBuilder out = new StringBuilder();
        out.append("# Traceability matrix (T090)\n\n");
        out.append("Generated by `scripts/trace-manifest.sh matrix` from specs/.../traceability/mapping-manifest.yml and the run exports in ")
                .append("docs/evidence/runs. Do not edit by hand.\n\n");
        out.append("Status: ").append(report.clean() ? "CLEAN" : "ORPHANS FOUND").append("\n\n```\n").append(report.describe()).append("\n```\n\n");

        Map<String, List<String>> families = new LinkedHashMap<>();
        FAMILIES.forEach(f -> families.put(f, new ArrayList<>()));
        for (String id : manifest.requirements().keySet()) {
            String family = id.substring(0, id.indexOf('-'));
            families.computeIfAbsent(family, f -> new ArrayList<>()).add(id);
        }
        out.append("# Requirement -> tasks, ADRs, tests, evidence\n\n");
        for (Map.Entry<String, List<String>> family : families.entrySet()) {
            if (family.getValue().isEmpty()) {
                continue;
            }
            out.append("## ").append(family.getKey()).append("\n\n| Requirement | Tasks | ADRs | Tests | Evidence | Status |\n|---|---|---|---|---|---|\n");
            for (String id : family.getValue()) {
                MappingManifest.Entry e = manifest.requirements().get(id);
                String status = report.requirementsWithoutEvidence().contains(id) ? "NO EVIDENCE" : "covered";
                out.append("| ").append(id).append(" | ").append(join(e.tasks())).append(" | ").append(join(e.adrs())).append(" | ")
                        .append(join(e.tests().stream().map(t -> simpleName(t.path())).toList())).append(" | ")
                        .append(join(e.evidence().stream().map(MappingManifest.EvidenceRef::path).toList())).append(" | ")
                        .append(status).append(" |\n");
            }
            out.append("\n");
        }

        Map<String, TreeSet<String>> testsToRequirements = new TreeMap<>();
        Map<String, TreeSet<String>> evidenceToRequirements = new TreeMap<>();
        manifest.requirements().forEach((id, e) -> {
            e.tests().forEach(t -> testsToRequirements.computeIfAbsent(t.path(), p -> new TreeSet<>()).add(id));
            e.evidence().forEach(v -> evidenceToRequirements.computeIfAbsent(v.path(), p -> new TreeSet<>()).add(id));
        });
        out.append("# Test -> requirements\n\n| Test | Requirements |\n|---|---|\n");
        testsToRequirements.forEach((path, ids) -> out.append("| `").append(path).append("` | ").append(String.join(", ", ids)).append(" |\n"));
        out.append("\n# Evidence file -> requirements\n\n| Evidence | Requirements |\n|---|---|\n");
        evidenceToRequirements.forEach((path, ids) -> out.append("| `").append(path).append("` | ").append(String.join(", ", ids)).append(" |\n"));

        out.append("\n# Demonstration runs (exported run records)\n\n")
                .append("| Run | Status | Class | Outcome | Audit chain | Policy outcomes | Human decisions | Evidence for |\n")
                .append("|---|---|---|---|---|---|---|---|\n");
        Path runs = root.resolve("docs/evidence/runs");
        if (Files.isDirectory(runs)) {
            try (Stream<Path> files = Files.list(runs)) {
                for (Path file : files.filter(f -> f.toString().endsWith(".json")).sorted().toList()) {
                    JsonNode doc = JSON.readTree(file.toFile());
                    JsonNode run = doc.path("run");
                    Map<String, Integer> outcomes = new LinkedHashMap<>();
                    for (String o : List.of("PASS", "FAIL", "EXCEPTION_REQUESTED", "NOT_APPLICABLE")) {
                        outcomes.put(o, 0);
                    }
                    doc.path("release_readiness").path("policy_outcomes").forEach(p -> outcomes.merge(p.path("outcome").asText(), 1, Integer::sum));
                    int human = 0;
                    for (JsonNode e : doc.path("history")) {
                        if (e.path("actor_type").asText().equals("HUMAN") && e.path("action").asText().equals("APPROVAL_DECIDED")) {
                            human++;
                        }
                    }
                    String relative = root.relativize(file).toString().replace('\\', '/');
                    out.append("| ").append(run.path("run_id").asText()).append(" | ").append(run.path("status").asText()).append(" | ")
                            .append(run.path("execution_class").asText()).append(" | ")
                            .append(run.hasNonNull("terminal_outcome") ? run.path("terminal_outcome").asText() : "-").append(" | ")
                            .append(doc.path("verify").path("verified").asBoolean() ? "intact" : "NOT VERIFIED").append(" (")
                            .append(doc.path("verify").path("event_count").asInt()).append(" events) | ")
                            .append(outcomes.get("PASS")).append(" PASS, ").append(outcomes.get("FAIL")).append(" FAIL, ")
                            .append(outcomes.get("EXCEPTION_REQUESTED")).append(" EXCEPTION_REQUESTED, ")
                            .append(outcomes.get("NOT_APPLICABLE")).append(" NOT_APPLICABLE | ").append(human).append(" | ")
                            .append(String.join(", ", evidenceToRequirements.getOrDefault(relative, new TreeSet<>()))).append(" |\n");
                }
            }
        }
        return out.toString();
    }

    private static String join(List<String> values) {
        return values.isEmpty() ? "-" : String.join(", ", values);
    }

    private static String simpleName(String path) {
        String file = path.substring(path.lastIndexOf('/') + 1);
        return file.endsWith(".java") ? file.substring(0, file.length() - 5) : file;
    }
}
