-- Application plane (T018; data-model.md, ADR-003). Uniqueness and integrity are enforced here, by the database,
-- not by application checks (PVT-003). IF NOT EXISTS keeps the script safe to re-run against an existing H2 file
-- after a restart (PVT-006). The control-plane tables are added by T019.

-- SHORT_LINK: short_code (UNIQUE NOT NULL); request_identity (UNIQUE NOT NULL - idempotency, FR-007);
-- payload_hash (original request, 409 conflict detection; retained for the life of the row);
-- expiry status is derived lazily at resolution, not stored (only expires_at is kept).
CREATE TABLE IF NOT EXISTS SHORT_LINK (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SHORT_CODE       VARCHAR(16)   NOT NULL,      -- 4-16 base-62 (contract)
    TARGET_URL       VARCHAR(2048) NOT NULL,      -- canonical form (FR-013, spec Appendix D)
    REQUEST_IDENTITY VARCHAR(64)   NOT NULL,      -- Idempotency-Key, 8-64 characters (contract)
    PAYLOAD_HASH     CHAR(64)      NOT NULL,      -- SHA-256 hex of the normalized request payload
    CREATED_AT       TIMESTAMP WITH TIME ZONE NOT NULL,
    EXPIRES_AT       TIMESTAMP WITH TIME ZONE NOT NULL,  -- explicit or CREATED_AT + default TTL (A-006)
    CONSTRAINT UK_SHORT_LINK_CODE UNIQUE (SHORT_CODE),
    CONSTRAINT UK_SHORT_LINK_REQUEST_IDENTITY UNIQUE (REQUEST_IDENTITY),
    CONSTRAINT CK_SHORT_LINK_EXPIRY CHECK (EXPIRES_AT > CREATED_AT)
);

-- REDIRECT_EVENT (FR-012): one row per resolution attempt; short_link_id is null exactly for NOT_FOUND events.
CREATE TABLE IF NOT EXISTS REDIRECT_EVENT (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SHORT_LINK_ID  BIGINT       NULL,
    ATTEMPTED_CODE VARCHAR(64)  NOT NULL,         -- requested code, length-capped by the application
    OCCURRED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    OUTCOME        VARCHAR(16)  NOT NULL,
    CONSTRAINT FK_REDIRECT_EVENT_LINK FOREIGN KEY (SHORT_LINK_ID) REFERENCES SHORT_LINK (ID),
    CONSTRAINT CK_REDIRECT_EVENT_OUTCOME CHECK (OUTCOME IN ('REDIRECTED', 'EXPIRED', 'NOT_FOUND')),
    CONSTRAINT CK_REDIRECT_EVENT_LINK CHECK ((OUTCOME = 'NOT_FOUND') = (SHORT_LINK_ID IS NULL))
);
CREATE INDEX IF NOT EXISTS IX_REDIRECT_EVENT_LINK ON REDIRECT_EVENT (SHORT_LINK_ID);

-- LOSS_REPORT (FR-015): quantified analytics capture failures per checkpoint period.
CREATE TABLE IF NOT EXISTS LOSS_REPORT (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERIOD_START     TIMESTAMP WITH TIME ZONE NOT NULL,
    PERIOD_END       TIMESTAMP WITH TIME ZONE NOT NULL,
    UNRECORDED_COUNT BIGINT NOT NULL,
    CONSTRAINT CK_LOSS_REPORT_COUNT CHECK (UNRECORDED_COUNT >= 0),
    CONSTRAINT CK_LOSS_REPORT_PERIOD CHECK (PERIOD_END >= PERIOD_START)
);

-- =====================================================================================================================
-- Control plane (T019; data-model.md "Control plane", ADR-005, ADR-007). All run-scoped rows carry RUN_ID (NFR-005).
-- No repository exposes update/delete on audit or workflow-history rows (FR-048); the hash chain (T021) detects
-- tampering below the repository layer. Enumerations are constrained to the values the data model lists.
-- =====================================================================================================================

-- WORKFLOW_RUN: run_revision (incremented on accepted replans; NOT_APPLICABLE rules bind node states to a revision).
-- STAGED_REVISION and the replan cap of 2 are deferred (L-SC-03); the columns stay for schema stability.
CREATE TABLE IF NOT EXISTS WORKFLOW_RUN (
    ID                VARCHAR(64)  PRIMARY KEY,           -- run / correlation identifier
    REQUIREMENT_REF   VARCHAR(128) NOT NULL,
    POLICY_VERSION    VARCHAR(64)  NOT NULL,              -- FR-032
    STATUS            VARCHAR(32)  NOT NULL,              -- state machine values enforced in code (T051/T053)
    RUN_REVISION      INT          NOT NULL,
    STAGED_REVISION   INT          NULL,
    VERSION           BIGINT       NOT NULL,              -- optimistic lock
    AUDIT_HEAD_HASH   CHAR(64)     NULL,
    AUDIT_EVENT_COUNT BIGINT       NOT NULL,              -- independent truncation reference (FR-048)
    CREATED_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
    TERMINAL_OUTCOME  VARCHAR(32)  NULL,
    SAFE_STOP_CAUSE   VARCHAR(32)  NULL,                  -- includes BOOT_RECOVERY
    EXECUTION_CLASS   VARCHAR(8)   NOT NULL,
    REPLAN_COUNT      INT          NOT NULL,
    CONSTRAINT CK_RUN_EXECUTION_CLASS CHECK (EXECUTION_CLASS IN ('LIVE', 'REPLAY')),
    CONSTRAINT CK_RUN_COUNTERS CHECK (RUN_REVISION >= 0 AND REPLAN_COUNT >= 0 AND AUDIT_EVENT_COUNT >= 0)
);

CREATE TABLE IF NOT EXISTS REQUIREMENT_ARTIFACT (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID         VARCHAR(64) NOT NULL REFERENCES WORKFLOW_RUN (ID),
    CONTENT        CLOB        NOT NULL,                  -- normalized requirement text
    PROVENANCE     VARCHAR(16) NOT NULL,
    VERSION        INT         NOT NULL,
    QUALITY_REPORT CLOB        NULL,
    ASSUMPTIONS    CLOB        NULL,
    CONSTRAINT CK_REQ_ARTIFACT_PROVENANCE CHECK (PROVENANCE IN ('CONFIRMED', 'DERIVED', 'PROPOSED'))
);

-- ARTIFACT: generic versioned artifact referenced by lineage rows; provenance labels per Constitution X.
CREATE TABLE IF NOT EXISTS ARTIFACT (
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID       VARCHAR(64) NOT NULL REFERENCES WORKFLOW_RUN (ID),
    TYPE         VARCHAR(32) NOT NULL,                    -- DESIGN, ADR, IMPACT_ANALYSIS, CODE, TEST, DOC, SUMMARY, ...
    VERSION      INT         NOT NULL,
    CONTENT_HASH CHAR(64)    NOT NULL,
    PROVENANCE   VARCHAR(32) NOT NULL,
    CREATED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT UK_ARTIFACT_VERSION UNIQUE (RUN_ID, TYPE, ID, VERSION),
    CONSTRAINT CK_ARTIFACT_PROVENANCE CHECK (PROVENANCE IN ('DETERMINISTIC', 'AI_ASSISTED_HUMAN_REVIEWED'))
);

CREATE TABLE IF NOT EXISTS STAGE_NODE (
    ID                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID                VARCHAR(64) NOT NULL REFERENCES WORKFLOW_RUN (ID),
    NODE_KEY              VARCHAR(8)  NOT NULL,           -- N01-N14
    STATUS                VARCHAR(32) NOT NULL,
    ATTEMPT_COUNT         INT         NOT NULL,
    RUN_REVISION          INT         NOT NULL,           -- bound at creation
    VERSION               BIGINT      NOT NULL,           -- optimistic lock
    ENTRY_STATE           VARCHAR(32) NULL,
    EXIT_STATE            VARCHAR(32) NULL,
    NOT_APPLICABLE_REASON VARCHAR(512) NULL,
    CONSTRAINT CK_STAGE_NODE_KEY CHECK (REGEXP_LIKE(NODE_KEY, '^N(0[1-9]|1[0-4])$')),
    CONSTRAINT CK_STAGE_NODE_ATTEMPTS CHECK (ATTEMPT_COUNT >= 0)
);

-- STAGE_EDGE: kind (DEPENDENCY, SYNC, CONDITIONAL).
CREATE TABLE IF NOT EXISTS STAGE_EDGE (
    ID        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID    VARCHAR(64) NOT NULL REFERENCES WORKFLOW_RUN (ID),
    FROM_NODE BIGINT      NOT NULL REFERENCES STAGE_NODE (ID),
    TO_NODE   BIGINT      NOT NULL REFERENCES STAGE_NODE (ID),
    KIND      VARCHAR(16) NOT NULL,
    CONSTRAINT CK_STAGE_EDGE_KIND CHECK (KIND IN ('DEPENDENCY', 'SYNC', 'CONDITIONAL')),
    CONSTRAINT CK_STAGE_EDGE_NO_SELF CHECK (FROM_NODE <> TO_NODE)
);

-- NODE_INPUT: exactly which artifact versions a stage read (resumption and replanning re-validation).
CREATE TABLE IF NOT EXISTS NODE_INPUT (
    NODE_ID              BIGINT      NOT NULL REFERENCES STAGE_NODE (ID),
    ARTIFACT_ID          BIGINT      NOT NULL REFERENCES ARTIFACT (ID),
    ARTIFACT_VERSION     INT         NOT NULL,
    CONTENT_HASH_AT_READ CHAR(64)    NOT NULL,
    ROLE                 VARCHAR(16) NOT NULL,
    RECORDED_AT          TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (NODE_ID, ARTIFACT_ID, ARTIFACT_VERSION),
    CONSTRAINT CK_NODE_INPUT_ROLE CHECK (ROLE IN ('INPUT', 'EVIDENCE', 'APPROVAL_REF'))
);

CREATE TABLE IF NOT EXISTS TASK (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID           VARCHAR(64)  NOT NULL REFERENCES WORKFLOW_RUN (ID),
    NODE_ID          BIGINT       NOT NULL REFERENCES STAGE_NODE (ID),
    TITLE            VARCHAR(256) NOT NULL,
    REQUIREMENT_REFS VARCHAR(512) NULL,
    STATUS           VARCHAR(32)  NOT NULL,
    EXECUTOR_CLASS   VARCHAR(16)  NOT NULL,
    CONSTRAINT CK_TASK_EXECUTOR CHECK (EXECUTOR_CLASS IN ('DETERMINISTIC', 'HUMAN_INGESTED'))
);

-- TASK_DEPENDENCY: (task_id, depends_on_task_id) composite PK - explicit dependency rows, not a list column (FR-036).
CREATE TABLE IF NOT EXISTS TASK_DEPENDENCY (
    TASK_ID            BIGINT NOT NULL REFERENCES TASK (ID),
    DEPENDS_ON_TASK_ID BIGINT NOT NULL REFERENCES TASK (ID),
    PRIMARY KEY (TASK_ID, DEPENDS_ON_TASK_ID),
    CONSTRAINT CK_TASK_DEPENDENCY_NO_SELF CHECK (TASK_ID <> DEPENDS_ON_TASK_ID)
);

-- OPERATION_RECORD: stable operation identity, the exactly-once mechanism of plan section 3.
CREATE TABLE IF NOT EXISTS OPERATION_RECORD (
    OPERATION_ID    VARCHAR(64) PRIMARY KEY,
    RUN_ID          VARCHAR(64) NOT NULL REFERENCES WORKFLOW_RUN (ID),
    NODE_ID         BIGINT      NOT NULL REFERENCES STAGE_NODE (ID),
    TYPE            VARCHAR(16) NOT NULL,
    STATUS          VARCHAR(16) NOT NULL,
    EFFECT_VERIFIED BOOLEAN     NOT NULL DEFAULT FALSE,   -- set by restart reconciliation
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    COMPLETED_AT    TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT CK_OPERATION_TYPE CHECK (TYPE IN ('ARTIFACT_WRITE', 'TEST_RUN', 'DOC_GENERATE', 'POLICY_EVAL', 'APPROVAL_REQUEST')),
    CONSTRAINT CK_OPERATION_STATUS CHECK (STATUS IN ('PENDING', 'COMPLETED', 'FAILED'))
);

-- FAILURE_EVENT: MTTR capture record (plan section 7); governance wait reported separately.
CREATE TABLE IF NOT EXISTS FAILURE_EVENT (
    ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID               VARCHAR(64) NOT NULL REFERENCES WORKFLOW_RUN (ID),
    NODE_ID              BIGINT      NOT NULL REFERENCES STAGE_NODE (ID),
    FAILURE_DETECTED_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    RECOVERY_START_AT    TIMESTAMP WITH TIME ZONE NULL,
    RECOVERY_COMPLETE_AT TIMESTAMP WITH TIME ZONE NULL,
    RECOVERY_MECHANISM   VARCHAR(8)  NULL,
    RECOVERED            BOOLEAN     NOT NULL,
    GOVERNANCE_WAIT_MS   BIGINT      NOT NULL DEFAULT 0,
    MTTR_EXCLUDED        BOOLEAN     NOT NULL DEFAULT FALSE,
    MTTR_EXCLUSION_REASON VARCHAR(256) NULL,
    CONSTRAINT CK_FAILURE_MECHANISM CHECK (RECOVERY_MECHANISM IS NULL OR RECOVERY_MECHANISM IN ('FP-1', 'FP-2', 'FP-3', 'FP-4')),
    CONSTRAINT CK_FAILURE_RECOVERED CHECK (NOT RECOVERED OR RECOVERY_COMPLETE_AT IS NOT NULL),
    CONSTRAINT CK_FAILURE_EXCLUSION CHECK (NOT MTTR_EXCLUDED OR MTTR_EXCLUSION_REASON IS NOT NULL)
);

-- APPROVAL: approver_key_id (must differ - FR-046).
CREATE TABLE IF NOT EXISTS APPROVAL (
    ID                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID                   VARCHAR(64) NOT NULL REFERENCES WORKFLOW_RUN (ID),
    KIND                     VARCHAR(32) NULL,
    GATE                     VARCHAR(4)  NULL,
    REQUESTER_KEY_ID         VARCHAR(64) NOT NULL,
    APPROVER_KEY_ID          VARCHAR(64) NULL,
    DECISION                 VARCHAR(16) NOT NULL,
    SCOPE                    VARCHAR(512) NULL,
    TIMEOUT_AT               TIMESTAMP WITH TIME ZONE NULL,
    SECOND_WINDOW_TIMEOUT_AT TIMESTAMP WITH TIME ZONE NULL,
    DECIDED_AT               TIMESTAMP WITH TIME ZONE NULL,
    AUTHORIZED_ARTIFACTS     VARCHAR(1024) NULL,
    REASON                   VARCHAR(1024) NULL,
    EVIDENCE_CLASS           VARCHAR(16) NOT NULL,
    CONSTRAINT CK_APPROVAL_GATE CHECK (REGEXP_LIKE(GATE, '^G[1-8]$')),
    CONSTRAINT CK_APPROVAL_KIND_OR_GATE CHECK (KIND IS NOT NULL OR GATE IS NOT NULL),
    CONSTRAINT CK_APPROVAL_DECISION CHECK (DECISION IN ('PENDING', 'APPROVED', 'REJECTED', 'ESCALATED')),
    CONSTRAINT CK_APPROVAL_EVIDENCE_CLASS CHECK (EVIDENCE_CLASS IN ('HUMAN', 'SIMULATED')),
    CONSTRAINT CK_APPROVAL_NOT_SELF CHECK (APPROVER_KEY_ID IS NULL OR APPROVER_KEY_ID <> REQUESTER_KEY_ID)
);

-- ACCEPTED_LIMITATION: individually approved (CL-5); validity rules (FR-037) enforced by the release logic.
CREATE TABLE IF NOT EXISTS ACCEPTED_LIMITATION (
    ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID               VARCHAR(64)   NOT NULL REFERENCES WORKFLOW_RUN (ID),
    DESCRIPTION          VARCHAR(1024) NOT NULL,
    APPROVAL_ID          BIGINT        NOT NULL REFERENCES APPROVAL (ID),
    COMPENSATING_CONTROL VARCHAR(1024) NULL,
    APPROVED_AT          TIMESTAMP WITH TIME ZONE NOT NULL
);

-- RELEASE_DECISION: one per run; the system recommends, the human decides (FR-037).
CREATE TABLE IF NOT EXISTS RELEASE_DECISION (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID           VARCHAR(64)   NOT NULL REFERENCES WORKFLOW_RUN (ID),
    RECOMMENDATION   VARCHAR(40)   NOT NULL,
    BLOCKING_REASONS VARCHAR(2048) NULL,
    DECISION         VARCHAR(16)   NOT NULL,
    REQUESTER_KEY_ID VARCHAR(64)   NULL,
    APPROVER_KEY_ID  VARCHAR(64)   NULL,
    DECIDED_AT       TIMESTAMP WITH TIME ZONE NULL,
    EVIDENCE_REF     VARCHAR(512)  NULL,
    CONSTRAINT UK_RELEASE_DECISION_RUN UNIQUE (RUN_ID),
    CONSTRAINT CK_RELEASE_RECOMMENDATION CHECK (RECOMMENDATION IN ('READY', 'READY_WITH_ACCEPTED_LIMITATIONS', 'NOT_READY')),
