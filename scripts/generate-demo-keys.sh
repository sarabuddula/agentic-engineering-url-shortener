#!/usr/bin/env bash
# Generates the four demo role keys (A-009, D-004). Demo-only, not production identity.
#
# Usage: eval "$(scripts/generate-demo-keys.sh)"
#
# stdout carries only `export` lines with the raw keys, so the keys live only in the
# caller's shell. The gitignored .demo-keys.yml receives key IDs, roles and SHA-256
# hashes only (NFR-001). Must run on macOS bash 3.2: no associative arrays, and
# `shasum -a 256` rather than `sha256sum`.
set -eu

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
out_file="${repo_root}/.demo-keys.yml"
tmp_file="${out_file}.tmp"

roles="ENGINEER APPROVER RELEASE_OWNER REVIEWER"

random_key() {
    od -An -tx1 -N32 /dev/urandom | tr -d ' \n'
}

sha256_hex() {
    printf '%s' "$1" | shasum -a 256 | cut -d' ' -f1
}

umask 077
{
    echo "# Generated by scripts/generate-demo-keys.sh. Demo-only (A-009)."
    echo "# Key IDs, roles and SHA-256 hashes only; raw keys are never written here (NFR-001)."
    echo "keys:"
} > "$tmp_file"

for role in $roles; do
    key="$(random_key)"
    key_id="demo-$(echo "$role" | tr 'A-Z_' 'a-z-')"
    {
        echo "  - key_id: ${key_id}"
        echo "    role: ${role}"
        echo "    key_hash: $(sha256_hex "$key")"
        echo "    label: demo-only"
    } >> "$tmp_file"
    echo "export ${role}_KEY=${key}"
done

mv "$tmp_file" "$out_file"
echo "Wrote key IDs, roles and hashes to ${out_file}" >&2
